// ============================================================
// Types for the Snapdeal AI Voice KAM application
// ============================================================

/** Status of the voice call */
export type CallStatus =
  | "idle"        // No call in progress
  | "connecting"  // Setting up APIs
  | "listening"   // Mic active, waiting for user speech
  | "processing"  // Sending to Jev + Gemini
  | "speaking"    // Bot is speaking via TTS
  | "ended";      // Call completed, showing summary

/** A single message in the conversation */
export interface Message {
  role: "user" | "assistant" | "system";
  content: string;
  timestamp: Date;
}

/** Jev classification result for a single choice question */
export interface JevChoiceResult {
  key: string;
  probabilities: Record<string, number>;
  confidence: number;
}

/** Jev noul (boolean probability) result */
export interface JevNoulResult {
  type: "noul";
  noul: number;
}

/** Combined Jev classification output after analyzing user utterance */
export interface JevAnalysis {
  intent: JevChoiceResult;
  isFrustrated: JevNoulResult;
  isUrgent: JevNoulResult;
  primaryIssue: JevChoiceResult;
  conversationStage: JevChoiceResult;
}

/** Seller metrics for a given period */
export interface PeriodMetrics {
  sales: number;
  orders: number;
  cancellationRate: number;
  avgSellingPrice: number;
  outOfStockProducts: number;
}

/** Full seller data with computed insights */
export interface SellerData {
  seller: { name: string; platform: string };
  metrics: {
    lastMonth: PeriodMetrics;
    thisMonth: PeriodMetrics;
  };
  computedInsights: {
    salesDeclinePct: number;
    orderDeclinePct: number;
    cancellationIncreasePct: number;
    oosIncreasePct: number;
    estimatedLostRevenueFromOOS: number;
    revenueLostToCancellations: number;
  };
}

/** End-of-call summary generated by the LLM */
export interface CallSummary {
  keyIssues: string[];
  recommendations: {
    action: string;
    expectedImpact: string;
    priority: "High" | "Medium" | "Low";
  }[];
  nextSteps: string[];
}

/** API keys required by the app */
export interface ApiKeys {
  geminiApiKey: string;
  jevApiKey: string;
}

